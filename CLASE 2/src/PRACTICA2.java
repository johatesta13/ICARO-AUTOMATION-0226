public class PRACTICA2
{
    public static void main() {

            System.out.println("Texto");   // String (texto)
            System.out.println(42);        // int (número entero)
            System.out.println(3.14);      // double (decimal)
            System.out.println('A');       // char (carácter)
            System.out.println(true);      // boolean (verdadero/falso)
            System.out.println(10 + 5);  // Operación matemática

            // suma de caracteres
        System.out.println("10" + "5");
        System.out.println("Johana" + "Testa");

        //System.out.println(10/0);

        System.out.println("Johana" + "Tea");
    }
}
